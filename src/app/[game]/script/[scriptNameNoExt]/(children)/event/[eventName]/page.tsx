export function generateStaticParams(): EventRouteParams[] {
    const params: EventRouteParams[] = [];
    for (const [game, gameData] of Object.entries(AllScriptsIndexed)) {
        for (const [scriptNameLowercase, scriptData] of Object.entries(gameData.scripts)) {
            for (const evtName of Object.keys(scriptData[AllSourcesCombined].events))
                params.push({game: prepareUrlPart(game), scriptNameNoExt: prepareUrlPart(scriptNameLowercase), eventName: prepareUrlPart(evtName)});
        }
    }

    return params;
}

export async function generateMetadata({params}: {readonly params: Promise<EventRouteParams>}): Promise<Metadata> {
    const {game, scriptBySources, evt} = getGameAndScriptAndEventFromParams(await params);

    const sourceIDs = Object.keys(scriptBySources);
    const sourceNames = sourceIDs.map(sourceId => AllScriptsIndexed[game].scriptSources[sourceId]!).sort(sourcesSortFn).map((source)=>SourceName({source, long: true}));

    if (sourceNames.length === 0) throw new Error('A script should have at least one source! Makes no sense for it to not have a source! Something is VERY wrong here.');
    const sourcesList = sourceNames.length === 1 ? sourceNames[0] : sourceNames.length === 2 ? sourceNames.join(' and ') : `${sourceNames.slice(0, -1).join(', ')}, and ${sourceNames.at(-1)}`;

    const scriptNamespaceName = getBestStringVariant(scriptBySources[AllSourcesCombined].namespaceName)![1];
    const description = await EventDocumentationStringRaw({game, evt, scriptName: scriptNamespaceName});

    const eventName = getBestStringVariant(evt.name)![1];

    return {
        title: eventName,
        description: `Reference page for the event ${scriptNamespaceName}.${eventName} for the game ${getGameName(game)}. This event is provided by the ${scriptNamespaceName} script found in ${sourcesList}.${description ? `\n\n${description}` : ''}`,
        // TODO: Add keywords relevant to the event.
        // Possibly break its name down into parts, take its parameters into account, return type, parent script, and all that fun stuff.
    };
}

