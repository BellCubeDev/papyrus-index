function Parameters({evt, ckWikiDataPromise, githubWikiDataPromise}: {readonly evt: PapyrusScriptEventOrBaseFunctionIndexedAggregate<PapyrusGame>, readonly ckWikiDataPromise: ReturnType<typeof getMediaWikiEventData>, readonly githubWikiDataPromise: Promise<Awaited<ReturnType<typeof getGitHubWikiEventData>>>}) {
    const ckWikiData = use(ckWikiDataPromise);
    const githubWikiData = use(githubWikiDataPromise);

    // eslint-disable-next-line react/no-unstable-nested-components -- these components are server components, so we don't really care
    return <GuardEmptyList replacement={null} Wrapper={({children}) => <>
        <br />
        <h2>Parameters</h2>
        <div data-analytics-id="docs-parameters" className={styles.parameters}>
            {children}
        </div>
    </>}>
        {evt.parameters.map((param, index) => {
            const lowercaseParamName = toLowerCase(param.name);
            const ckWikiParamData = ckWikiData?.parameters[index];

            const githubWikiParamDatas = githubWikiData?.map(([sourceIdentifier, wikiData]) => {
                const firstPass = wikiData.parameters[lowercaseParamName];
                if (firstPass) return [sourceIdentifier, firstPass] as const;

                if (lowercaseParamName.startsWith('a_')) { // Some sources prefix all of their parameters with 'a_', but don't do so in the wiki
                    const withoutPrefix = lowercaseParamName.slice(2) as Lowercase<string>;
                    const secondPass = wikiData.parameters[withoutPrefix];
                    if (secondPass) return [sourceIdentifier, secondPass] as const;
                }

                return null;
            }).filter((v): v is NonNullable<typeof v> => v !== null) ?? [];

            return <div key={param.name}>
                <h3>
                    {param.isRequired
                        ? <PapyrusTypeNamed game={evt.game.game} name={param.name} type={param.value} />
                        : <PapyrusTypeWithValue game={evt.game.game} type={param.value} name={param.name} />}
                </h3>
                {ckWikiParamData?.descriptionMarkdown ? <>
                    <h4>CK Wiki Description</h4>
                    <WikiMarkdown data-analytics-id="docs-parameter-description-ckwiki" gameData={evt.game} md={ckWikiParamData.descriptionMarkdown} baseURL={ckWikiData!.wikiPageUrl} />
                </> : null}
                {githubWikiParamDatas.filter(([,wikiData]) => wikiData.descriptionMD).map(([sourceIdentifier, paramWikiData]) =>
                    <Fragment key={sourceIdentifier}>
                        <h4>GitHub Wiki Description (<SourceName source={evt.game.scriptSources[sourceIdentifier]!} />)</h4>
                        <WikiMarkdown data-analytics-id="docs-parameter-description-githubwiki" gameData={evt.game}
                            md={paramWikiData.descriptionMD!} baseURL={paramWikiData.linkToWikiData} />
                    </Fragment>
                )}
            </div>;
        })}
    </GuardEmptyList>;
}

function RelatedPages({gameData, ckWikiDataPromise, githubWikiDataPromise}: {readonly gameData: PapyrusGameDataIndexed<PapyrusGame>, readonly ckWikiDataPromise: ReturnType<typeof getMediaWikiEventData>, readonly githubWikiDataPromise: Promise<Awaited<ReturnType<typeof getGitHubWikiEventData>>>}) {
    const ckWikiData = use(ckWikiDataPromise);
    const githubWikiData = use(githubWikiDataPromise);

    let seeAlsoMd = ckWikiData?.seeAlsoMarkdown ?? '';

    const dedupedLinks = new Set<string>();
    for (const [, wikiData] of githubWikiData) {
        for (const link of wikiData.seeAlso) {
            if (dedupedLinks.has(link.uri)) continue;
            seeAlsoMd += `\n- [${link.name}](${link.uri})\n`;
            dedupedLinks.add(link.uri);
        }
    }

    // eslint-disable-next-line react/no-unstable-nested-components -- these components are server components, so we don't really care
    return <GuardEmptyList replacement={null} Wrapper={({children}) => <>
        <br />
        <div data-analytics-id="docs-related">
            <h2>Related Pages</h2>
            {children}
        </div>
    </>}>
        {seeAlsoMd.length === 0 ? [] : <WikiMarkdown gameData={gameData} md={seeAlsoMd} baseURL={ckWikiData?.wikiPageUrl ?? AUTOMATIC_BASE_URL} />}
    </GuardEmptyList>;
}

function AdditionalReferences({game, ckWikiDataPromise, githubWikiDataPromise}: {readonly game: PapyrusGame, readonly ckWikiDataPromise: ReturnType<typeof getMediaWikiEventData>, readonly githubWikiDataPromise:Promise<Awaited<ReturnType<typeof getGitHubWikiEventData>>>}) {
    const ckWikiData = use(ckWikiDataPromise);
    const githubWikiData = use(githubWikiDataPromise);

    // eslint-disable-next-line react/no-unstable-nested-components -- these components are server components, so we don't really care
    return <GuardEmptyList replacement={null} Wrapper={({children}) => <>
        <br />
        <div data-analytics-id="docs-additional-references">
            <h2>Additional References</h2>
            {children}
        </div>
    </>}>
        {...[
            ckWikiData?.wikiPageUrl && <p key="ck-wiki-link"><a href={ckWikiData.wikiPageUrl} target="_blank" rel="noopener noreferrer">View this event&rsquo;s page on the {ckWikiData.wikiName}</a></p>,
            ...githubWikiData.map(([sourceIdentifier, wikiData]) =>
                <p key={wikiData.linkToWikiData}>
                    <a href={wikiData.linkToWikiData} target="_blank" rel="noopener noreferrer">View this event on the GitHub Wiki for <SourceName long source={AllScriptsIndexed[game].scriptSources[sourceIdentifier]!} /></a>
                </p>
            )
        ].filter(Boolean)}
    </GuardEmptyList>;

}

function RegistrationFunctions({evt, githubWikiDataPromise}: {readonly evt: PapyrusScriptEventOrBaseFunctionIndexedAggregate<PapyrusGame>, readonly githubWikiDataPromise: Promise<Awaited<ReturnType<typeof getGitHubWikiEventData>>>}) {
    const githubWikiData = use(githubWikiDataPromise);

    const knownRegistrationFunctions = Array.from(
        githubWikiData.flatMap(([, wikiData]) => wikiData.registrationControlFunctions).filter((f):f is Exclude<typeof f, null> => f !== null)
    );

    // TODO: Add "guessed" registration functions

    const registrationFunctions = Array.from(new Map<string, {name: string, func: PapyrusScriptFunctionIndexedAggregate<PapyrusGame> | undefined}>(
        knownRegistrationFunctions.map((funcName) => [funcName, {name: funcName, func: evt.script.functions[funcName]}])
    ));

    if (registrationFunctions.length === 0) return null;

    return <div data-analytics-id="docs-registration-functions">
        <h2>Registration Control Functions</h2>
        <ul>
            {registrationFunctions.map(([funcName, {name, func}]) => {
                if (func) {
                    return <li key={funcName}>
                        <PapyrusScriptFunctionReference game={evt.game.game} funcAggregate={func} scriptAggregate={evt.script} />
                    </li>;
                } else {
                    return <li key={funcName}>
                        <NotFoundChip /> {name}
                    </li>;
                }
            })}
        </ul>
    </div>;
}